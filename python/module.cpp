SparseCSC csc_from_arrays(py::array_t<int64_t> indptr, py::array_t<int64_t> indices,
                          py::array_t<double> data, idx_t rows, idx_t cols) {
  SparseCSC M(rows, cols);
  auto ip = indptr.unchecked<1>(); auto ix = indices.unchecked<1>(); auto v = data.unchecked<1>();
  M.colptr.assign(cols + 1, 0);
  for (idx_t j = 0; j <= cols; ++j) M.colptr[j] = ip(j);
  const idx_t nnz = M.colptr[cols];
  M.rowind.resize(nnz); M.values.resize(nnz);
  for (idx_t k = 0; k < nnz; ++k) { M.rowind[k] = ix(k); M.values[k] = v(k); }
  return M;
}

std::vector<double> vec_from_array(py::array_t<double> a) {
  auto r = a.unchecked<1>();
  std::vector<double> v((size_t)r.shape(0));
  for (ssize_t i = 0; i < r.shape(0); ++i) v[i] = r(i);
  return v;
}

py::array_t<double> array_from_vec(const std::vector<double>& v) {
  py::array_t<double> a((ssize_t)v.size());
  auto r = a.mutable_unchecked<1>();
  for (size_t i = 0; i < v.size(); ++i) r((ssize_t)i) = v[i];
  return a;
}

